import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { AuthProvider } from '@/context/AuthContext';
import LoginPage from '@/pages/Login';
import { VerificationCard } from '@/components/complex/VerificationCard';
import { PasswordResetFlow } from '@/components/complex/PasswordResetFlow';
const resetState = vi.hoisted(() => ({ step: 'email', status: 'idle', message: '', desafio: null, solicitarCodigo: vi.fn(), verificarCodigo: vi.fn(), reenviarCodigo: vi.fn(), confirmarSenha: vi.fn(), voltar: vi.fn() }));
vi.mock('@/hooks/usePasswordReset', () => ({ usePasswordReset: () => resetState }));
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it('login valida campos, envia credenciais e apresenta desafio OTP', async () => {
 localStorage.clear();
 vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify({ challenge_id: 'c1', masked_email: 'a***@x.com', expires_in: 300 }))));
 const view = render(<MemoryRouter><AuthProvider><LoginPage /></AuthProvider></MemoryRouter>);
 fireEvent.submit(view.container.querySelector('form')!);
 expect(screen.getByText('Informe seu e-mail')).toBeTruthy();
 fireEvent.change(screen.getByLabelText('E-mail'), { target: { value: 'ana@x.com' } });
 fireEvent.change(screen.getByLabelText('Senha'), { target: { value: 'secret123' } });
 fireEvent.submit(view.container.querySelector('form')!);
 expect(await screen.findByText('Verifique seu e-mail')).toBeTruthy();
});
it('OTP permite colar, reenviar e voltar', async () => {
 const verify = vi.fn(); const resend = vi.fn().mockResolvedValue(undefined); const back = vi.fn();
 const view = render(<VerificationCard maskedEmail="a***@x.com" status="error" message="Código inválido" onVerify={verify} onResend={resend} onBack={back} cooldownSeconds={0} isMock />);
 fireEvent.paste(screen.getAllByRole('textbox')[0], { clipboardData: { getData: () => '123456' } });
 expect(verify).toHaveBeenCalledWith('123456');
 fireEvent.submit(view.container.querySelector('form')!);
 expect(verify).toHaveBeenCalledTimes(2);
 const buttons = screen.getAllByRole('button');
 for (const button of buttons) if (/reenviar/i.test(button.textContent!)) fireEvent.click(button);
 await waitFor(() => expect(resend).toHaveBeenCalled());
 for (const button of buttons) if (/voltar/i.test(button.textContent!)) fireEvent.click(button);
 expect(back).toHaveBeenCalled();
});
it('redefinição valida email, confirmação de senha e conclusão', () => {
 resetState.step = 'email'; const close = vi.fn();
 const view = render(<PasswordResetFlow onClose={close} />);
 fireEvent.submit(view.container.querySelector('form')!); expect(screen.getByText('Informe um e-mail válido.')).toBeTruthy();
 fireEvent.change(view.container.querySelector('input')!, { target: { value: 'a@x.com' } });
 fireEvent.submit(view.container.querySelector('form')!); expect(resetState.solicitarCodigo).toHaveBeenCalledWith('a@x.com');
 resetState.step = 'new-password'; view.rerender(<PasswordResetFlow onClose={close} />);
 const inputs = view.container.querySelectorAll('input');
 fireEvent.change(inputs[0], { target: { value: 'Abcd1234!' } }); fireEvent.change(inputs[1], { target: { value: 'wrong' } });
 fireEvent.submit(view.container.querySelector('form')!); expect(screen.getByText('As senhas não conferem.')).toBeTruthy();
 fireEvent.change(inputs[1], { target: { value: 'Abcd1234!' } }); fireEvent.submit(view.container.querySelector('form')!);
 expect(resetState.confirmarSenha).toHaveBeenCalledWith('Abcd1234!');
 const toggles = screen.getAllByRole('button', { name: 'Mostrar senha' });
 fireEvent.click(toggles[0]); expect(inputs[0].type).toBe('text'); expect(inputs[1].type).toBe('password');
 fireEvent.click(screen.getByRole('button', { name: 'Ocultar senha' })); expect(inputs[0].type).toBe('password');
});
